/**
 * Markdown architecture report generated from an analysis result.
 */
import { KIND_META } from "../presentation.ts";
import { indexGraph } from "../queries/graph-index.ts";
import { flowPaths, traceFlow } from "../queries/flows.ts";
import type { AnalysisResult, NodeKind } from "../types.ts";
import { toMermaid } from "./mermaid.ts";

const cell = (s: string | number | undefined) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const code = (s: string | undefined) => (s ? `\`${s.replace(/`/g, "'")}\`` : "");

export const LIMITATIONS = [
  "Results come from static analysis of source files. The project is never executed, so runtime-only behaviour (dynamic imports with computed paths, reflection, string-based lookups, event buses, environment-dependent URLs) is not observed.",
  "Relationships marked *inferred* rely on heuristics such as URL pattern matching between client requests and route handlers, prop-callback forwarding and HTTP clients identified by name.",
  "Impact analysis lists *potential* impact based on detected dependencies; it can neither guarantee that listed items break nor that unlisted items are safe.",
  "Supported today: TypeScript and JavaScript (including JSX/TSX), React and Next.js conventions, fetch/axios requests, Prisma-style and literal-SQL database access.",
];

export function toMarkdown(result: AnalysisResult): string {
  const index = indexGraph(result);
  const out: string[] = [];
  const name = (id: string | null | undefined) => (id ? (index.nodes.get(id)?.name ?? id) : "—");

  out.push(`# ${result.project.name} — Architecture report`);
  out.push("");
  out.push(`Generated by Interface Archaeology ${result.analyzerVersion} on ${result.generatedAt}. Static analysis of ${result.stats.filesAnalyzed} files (${result.stats.totalLoc.toLocaleString("en")} lines) in ${result.durationMs} ms.`);
  out.push("");
  out.push("## Overview");
  out.push("");
  out.push(`- **Framework:** ${result.framework.label}${result.framework.version ? ` ${result.framework.version}` : ""}${result.framework.router ? ` (App Router: ${result.framework.router.app ? "yes" : "no"}, Pages Router: ${result.framework.router.pages ? "yes" : "no"})` : ""}`);
  out.push(`- **Language:** ${result.framework.language}`);
  out.push(`- **Detection signals:** ${result.framework.signals.join("; ")}`);
  const kinds = (Object.entries(result.stats.nodesByKind) as [NodeKind, number][]).map(([k, v]) => `${v} ${KIND_META[k].plural.toLowerCase()}`).join(", ");
  out.push(`- **Discovered:** ${kinds}`);
  out.push(`- **Relationships:** ${result.edges.length} (${result.edges.filter((e) => e.confidence === "inferred").length} inferred)`);
  out.push("");

  if (result.routes.length) {
    out.push("## Routes");
    out.push("");
    out.push("| Route | Kind | Router | File | Methods |");
    out.push("| --- | --- | --- | --- | --- |");
    for (const r of result.routes) out.push(`| ${code(r.path)} | ${r.kind} | ${r.router} | ${code(r.file)} | ${cell(r.methods?.join(", "))} |`);
    out.push("");
  }

  out.push("## Component structure");
  out.push("");
  const groups: NodeKind[] = ["layout", "page", "route-segment", "provider", "component", "context", "hook", "service", "server-action", "route-handler", "middleware", "utility"];
  for (const kind of groups) {
    const nodes = result.nodes.filter((n) => n.kind === kind).sort((a, b) => a.name.localeCompare(b.name));
    if (!nodes.length) continue;
    out.push(`### ${KIND_META[kind].plural}`);
    out.push("");
    for (const n of nodes) {
      const renders = (index.out.get(n.id) ?? []).filter((e) => e.kind === "renders" || e.kind === "lazy-loads").map((e) => name(e.target));
      const extra = [
        n.props?.length ? `props: ${n.props.map((p) => p.name).join(", ")}` : "",
        n.state?.length ? `state: ${n.state.map((s) => s.name).join(", ")}` : "",
        renders.length ? `renders: ${[...new Set(renders)].join(", ")}` : "",
        n.renderEnv ? n.renderEnv.env : "",
      ].filter(Boolean);
      out.push(`- **${n.name}** — ${code(`${n.file}:${n.line}`)}${extra.length ? ` · ${extra.join(" · ")}` : ""}`);
    }
    out.push("");
  }

  out.push("## API inventory");
  out.push("");
  if (!result.network.length) out.push("No network calls were detected in the analyzed files.");
  else {
    out.push("| Method | Endpoint | Called from | Location | Handled by | Confidence |");
    out.push("| --- | --- | --- | --- | --- | --- |");
    for (const n of result.network) {
      const handlers = n.endpointId ? (index.out.get(n.endpointId) ?? []).filter((e) => e.kind === "handled-by").map((e) => name(e.target)) : [];
      out.push(`| ${n.method} | ${code(n.url ?? n.rawUrl)} | ${cell(name(n.callerId))}${n.callerMember ? `.${n.callerMember}` : ""} | ${code(`${n.file}:${n.line}`)} | ${cell(handlers.join(", ") || "—")} | ${n.confidence} |`);
    }
  }
  out.push("");

  const events = result.nodes.filter((n) => n.kind === "event");
  if (events.length) {
    out.push("## Interaction flows");
    out.push("");
    for (const ev of events) {
      const flow = traceFlow(result, ev.id, index);
      if (!flow) continue;
      const owner = (index.in.get(ev.id) ?? []).find((e) => e.kind === "handles");
      out.push(`### ${ev.name} in ${name(owner?.source)}`);
      out.push("");
      for (const path of flowPaths(flow)) {
        out.push(`- ${path.map((s) => `${name(s.nodeId)}${s.member ? `.${s.member}` : ""}`).join(" → ")}${path.some((s) => s.via?.confidence === "inferred") ? " _(includes inferred steps)_" : ""}`);
      }
      if (ev.stateUpdates?.length) out.push(`- State updates: ${ev.stateUpdates.join(", ")}`);
      for (const gap of new Set(flow.gaps)) out.push(`- ⚠ ${gap}`);
      out.push("");
    }
  }

  out.push("## Dependencies");
  out.push("");
  out.push(`- Maximum dependency depth: ${result.dependencies.maxDepth}`);
  out.push(`- Import cycles: ${result.dependencies.cycles.length}`);
  for (const c of result.dependencies.cycles) out.push(`  - ${c.map((f) => code(f)).join(" ↔ ")}`);
  out.push(`- Isolated modules (no imports in or out): ${result.dependencies.isolated.length ? result.dependencies.isolated.map(code).join(", ") : "none"}`);
  out.push("");
  out.push("| Most connected files | Imported by | Imports |");
  out.push("| --- | --- | --- |");
  for (const h of result.dependencies.hubs.slice(0, 10)) out.push(`| ${code(h.file)} | ${h.fanIn} | ${h.fanOut} |`);
  out.push("");
  const packages = result.nodes.filter((n) => n.kind === "external");
  if (packages.length) {
    out.push(`External packages referenced by symbols: ${packages.map((p) => `${code(p.name)}${p.version ? ` (${p.version})` : ""}`).join(", ")}`);
    out.push("");
  }

  out.push("## Architecture diagram");
  out.push("");
  out.push("```mermaid");
  out.push(toMermaid(result).trimEnd());
  out.push("```");
  out.push("");

  const warnings = result.diagnostics.filter((d) => d.severity !== "info");
  out.push("## Analysis notes");
  out.push("");
  out.push(`${result.diagnostics.length} diagnostics (${warnings.length} warnings or errors).`);
  for (const d of warnings.slice(0, 50)) out.push(`- ${d.severity}: ${d.message}${d.file ? ` — ${code(`${d.file}${d.line ? `:${d.line}` : ""}`)}` : ""}`);
  out.push("");
  out.push("## Limitations");
  out.push("");
  for (const l of LIMITATIONS) out.push(`- ${l}`);
  out.push("");
  return out.join("\n");
}
